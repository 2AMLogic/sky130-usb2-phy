#!/usr/bin/env python3
"""Regenerate dplus_pullup_mm.spice from design/netlist/dplus_pullup.spice (stdlib only).

The pinned sky130 library has no local-mismatch model for sky130_fd_pr__res_generic_po, the
ladder resistor of the D+ pull-up. This swaps each instance for the testbench wrapper
`usb_res_po_mm` (pull-up mismatch testbench deck), which draws a per-instance relative error.

    python3 make_mm_netlist.py           # rewrite the file
    python3 make_mm_netlist.py --check   # exit 1 if the committed file is stale
"""

import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parents[2] / "design" / "netlist" / "dplus_pullup.spice"
DST = HERE / "dplus_pullup_mm.spice"
HEADER = ("* dplus_pullup_mm -- design/netlist/dplus_pullup.spice with every sky130_fd_pr__res_generic_po instance replaced by the\n"
          "* mismatch wrapper usb_res_po_mm (defined in the testbench deck). Generated by make_mm_netlist.py; do not edit.\n")


def render() -> str:
    # the explicit `m=1` on the instance lines is dropped: an X-line `m` overrides the wrapper's own
    # per-instance multiplier, which is how the spread is applied
    text = SRC.read_text().replace("sky130_fd_pr__res_generic_po", "usb_res_po_mm")
    return HEADER + re.sub(r"(usb_res_po_mm W=\S+ L=\S+) m=1", r"\1", text)


if __name__ == "__main__":
    text = render()
    if "--check" in sys.argv:
        raise SystemExit(0 if DST.read_text() == text else 1)
    DST.write_text(text)
